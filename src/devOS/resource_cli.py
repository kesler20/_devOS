import argparse
import pathlib
import sys

from devOS.domain import generated_artifact
from devOS.domain import relational
from devOS.domain import resource_api
from devOS.infrastructure import resource_loader
from devOS.use_cases import generate_relational_dao
from devOS.use_cases import generate_resource_api
from devOS.use_cases import generate_resource_dtos
from devOS.use_cases import generate_test_scaffolds


def main(arguments: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="dev build")
    commands = parser.add_subparsers(dest="command", required=True)
    dao = commands.add_parser("dao", help="Generate DAOs from a relational document")
    dao.add_argument("document", type=pathlib.Path)
    dao.add_argument("--output", type=pathlib.Path, required=True)
    tests = commands.add_parser("tests")
    test_commands = tests.add_subparsers(dest="test_kind", required=True)
    for kind in ["api", "services"]:
        scaffold = test_commands.add_parser(kind)
        scaffold.add_argument("source", type=pathlib.Path)
        scaffold.add_argument("--module", required=True)
        scaffold.add_argument("--app-name", default="app")
        scaffold.add_argument("--output", type=pathlib.Path, required=True)
    contract_parser = test_commands.add_parser("contracts")
    contract_parser.add_argument("dao_module")
    contract_parser.add_argument(
        "--python-root", type=pathlib.Path, default=pathlib.Path("src")
    )
    contract_parser.add_argument("--dto-module", required=True)
    contract_parser.add_argument("--output", type=pathlib.Path, required=True)
    for command in ["dto", "api"]:
        subparser = commands.add_parser(command)
        subparser.add_argument("dao_module")
        subparser.add_argument(
            "--python-root", type=pathlib.Path, default=pathlib.Path("src")
        )
        if command == "dto":
            subparser.add_argument("--python-output", type=pathlib.Path, required=True)
            subparser.add_argument(
                "--typescript-output", type=pathlib.Path, required=True
            )
        else:
            subparser.add_argument("--dto-module", required=True)
            subparser.add_argument("--crud-module", required=True)
            subparser.add_argument("--session-module", required=True)
            subparser.add_argument("--session-provider", default="get_session")
            subparser.add_argument("--output", type=pathlib.Path, required=True)
    options = parser.parse_args(arguments)
    try:
        if options.command == "tests" and options.test_kind in {"api", "services"}:
            if options.output.exists():
                raise ValueError(
                    f"Preserving project-owned tests at {options.output}. Choose a new scaffold path"
                )
            source = options.source.read_text(encoding="utf-8")
            content = generate_test_scaffolds.GenerateTestScaffoldsUseCase().execute(
                source, options.module, options.test_kind, options.app_name
            )
            artifacts = [
                generated_artifact.GeneratedArtifact(
                    options.output, content, "# Project-owned test scaffold."
                )
            ]
            inputs = [options.source]
        elif options.command == "dao":
            document = relational.SchemaDocument.model_validate_json(
                options.document.read_text(encoding="utf-8")
            )
            source = generate_relational_dao.GenerateRelationalDaoUseCase().execute(
                document
            )
            artifacts = [
                generated_artifact.GeneratedArtifact(
                    options.output,
                    source,
                    "# Generated by devOS from the relational SchemaDocument.",
                )
            ]
            inputs = [options.document]
        else:
            # Validate import names before executing the selected local DAO module.
            if options.command == "api":
                imports = resource_api.ResourceApiImports(
                    dao_module=options.dao_module,
                    dto_module=options.dto_module,
                    crud_module=options.crud_module,
                    session_module=options.session_module,
                    session_provider=options.session_provider,
                )
                resource_loader.validate_support(
                    options.python_root, imports.crud_module
                )
                for name in [imports.dto_module, imports.session_module]:
                    if not resource_loader.get_module_path(
                        options.python_root, name
                    ).is_file():
                        raise ValueError(f"Required consumer module {name} is missing")
            elif any(not part.isidentifier() for part in options.dao_module.split(".")):
                raise ValueError("DAO module must be a dotted Python module name")
            resources = resource_loader.load_resources(
                options.python_root, options.dao_module
            )
            inputs = [
                resource_loader.get_module_path(options.python_root, options.dao_module)
            ]
            if options.command == "tests":
                if any(
                    not part.isidentifier() for part in options.dto_module.split(".")
                ):
                    raise ValueError("DTO module must be a dotted Python module name")
                content = (
                    generate_test_scaffolds.GenerateResourceTestsUseCase().execute(
                        resources, options.dto_module
                    )
                )
                inputs.append(
                    resource_loader.get_module_path(
                        options.python_root, options.dto_module
                    )
                )
                artifacts = [
                    generated_artifact.GeneratedArtifact(
                        options.output,
                        content,
                        "# Generated by devOS from SQLAlchemy DAO metadata.",
                    )
                ]
            elif options.command == "dto":
                contracts = (
                    generate_resource_dtos.GenerateResourceDtosUseCase().execute(
                        resources
                    )
                )
                artifacts = [
                    generated_artifact.GeneratedArtifact(
                        options.python_output,
                        contracts.python,
                        "# Generated by devOS from SQLAlchemy DAO metadata.",
                    ),
                    generated_artifact.GeneratedArtifact(
                        options.typescript_output,
                        contracts.typescript,
                        "// Generated by devOS from SQLAlchemy DAO metadata.",
                    ),
                ]
            else:
                inputs.extend(
                    resource_loader.get_module_path(options.python_root, name)
                    for name in [
                        imports.dto_module,
                        imports.crud_module,
                        imports.session_module,
                    ]
                )
                content = generate_resource_api.GenerateResourceApiUseCase().execute(
                    resources, imports
                )
                artifacts = [
                    generated_artifact.GeneratedArtifact(
                        options.output,
                        content,
                        "# Generated by devOS from SQLAlchemy DAO metadata.",
                    )
                ]
        resource_loader.write_artifacts(artifacts, inputs)
        return 0
    except (OSError, ValueError, ImportError) as error:
        print(str(error), file=sys.stderr)
        return 1
