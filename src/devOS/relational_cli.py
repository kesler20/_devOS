import argparse
import pathlib
import sys

import pydantic

from devOS.domain import relational
from devOS.domain import generated_artifact
from devOS.infrastructure import resource_loader
from devOS.use_cases import generate_relational_contracts
from devOS.use_cases import generate_relational_sql
from devOS.use_cases import import_relational_sql


def main(arguments: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="dev schema")
    commands = parser.add_subparsers(dest="command", required=True)
    validate = commands.add_parser("validate")
    validate.add_argument("document", type=pathlib.Path)
    sql = commands.add_parser("sql")
    sql.add_argument("document", type=pathlib.Path)
    sql.add_argument("--output", type=pathlib.Path, required=True)
    initialize = commands.add_parser("import-sql")
    initialize.add_argument("sql", type=pathlib.Path)
    initialize.add_argument("--output", type=pathlib.Path, required=True)
    contracts = commands.add_parser("contracts")
    contracts.add_argument("--json-schema", type=pathlib.Path, required=True)
    contracts.add_argument("--typescript", type=pathlib.Path, required=True)
    options = parser.parse_args(arguments)
    try:
        if options.command == "import-sql":
            if options.output.exists():
                raise ValueError(
                    f"Document already exists: {options.output}. SQL import only initializes new documents"
                )
            document = import_relational_sql.ImportRelationalSqlUseCase().execute(
                options.sql.read_text(encoding="utf-8")
            )
            options.output.parent.mkdir(parents=True, exist_ok=True)
            with options.output.open("x", encoding="utf-8") as destination:
                destination.write(document.model_dump_json(indent=2) + "\n")
        elif options.command == "validate":
            relational.SchemaDocument.model_validate_json(
                options.document.read_text(encoding="utf-8")
            )
            print("Valid relational document")
        elif options.command == "sql":
            document = relational.SchemaDocument.model_validate_json(
                options.document.read_text(encoding="utf-8")
            )
            output = generate_relational_sql.GenerateRelationalSqlUseCase().execute(
                document
            )
            resource_loader.write_artifacts(
                [
                    generated_artifact.GeneratedArtifact(
                        options.output,
                        output,
                        "-- Generated by devOS from the relational SchemaDocument.",
                    )
                ],
                [options.document],
            )
        else:
            artifacts = (
                generate_relational_contracts.GenerateRelationalContractsUseCase().execute()
            )
            if options.json_schema.resolve() == options.typescript.resolve():
                raise ValueError(
                    "JSON Schema and TypeScript outputs must be different files"
                )
            for destination in (options.json_schema, options.typescript):
                if destination.exists() and not destination.is_file():
                    raise ValueError(f"Output must be a file: {destination}")
            resource_loader.write_artifacts(
                [
                    generated_artifact.GeneratedArtifact(
                        options.json_schema, artifacts.json_schema, '{\n  "$defs":'
                    ),
                    generated_artifact.GeneratedArtifact(
                        options.typescript,
                        artifacts.typescript,
                        "// Generated from devOS.domain.relational.SchemaDocument.",
                    ),
                ],
                [],
            )
        return 0
    except (OSError, ValueError, pydantic.ValidationError) as error:
        print(str(error), file=sys.stderr)
        return 1
