import ast
import logging

from devOS.domain import resource_schema

PYTHON_WIRE_TYPES = r"""# Generated by devOS from SQLAlchemy DAO metadata.
import base64
import datetime
import enum
import math
import re
import typing

import pydantic


INTEGER_PATTERN = r"^-?[0-9]+$"
NUMERIC_PATTERN = r"^[+-]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?$"
UUID_PATTERN = r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$"
TIME_PATTERN = r"^(?:[01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9](?:\.[0-9]{1,6})?(?:Z|[+-](?:0[0-9]|1[0-5]):[0-5][0-9])?$"
DATETIME_PATTERN = r"^[0-9]{4}-[0-9]{2}-[0-9]{2}T(?:[01][0-9]|2[0-3]):[0-5][0-9](?::[0-5][0-9](?:\.[0-9]{1,6})?)?(?:Z|[+-](?:0[0-9]|1[0-5]):[0-5][0-9])?$"
DURATION_PATTERN = r"^-?P(?=[0-9]|T[0-9])(?:[0-9]+(?:\.[0-9]+)?Y)?(?:[0-9]+(?:\.[0-9]+)?M)?(?:[0-9]+(?:\.[0-9]+)?W)?(?:[0-9]+(?:\.[0-9]+)?D)?(?:T(?=[0-9])(?:[0-9]+(?:\.[0-9]+)?H)?(?:[0-9]+(?:\.[0-9]+)?M)?(?:[0-9]+(?:\.[0-9]+)?S)?)?$"
BYTES_PATTERN = r"^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$"


def validate_integer(value: object) -> int:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError("Expected a JSON integer")
    if isinstance(value, float) and (not math.isfinite(value) or not value.is_integer()):
        raise ValueError("Expected a JSON integer")
    return int(value)


def validate_big_integer(value: str) -> str:
    if not -9223372036854775808 <= int(value) <= 9223372036854775807:
        raise ValueError("Bigint must fit the signed 64-bit PostgreSQL range")
    return value


def validate_date(value: str) -> str:
    datetime.date.fromisoformat(value)
    return value


def validate_datetime(value: str) -> str:
    datetime.datetime.fromisoformat(value)
    time = value.split("T", 1)[1]
    if (value.endswith("Z") or re.search(r"[+-][0-9]{2}:[0-9]{2}$", value)) and time[5:6] != ":":
        raise ValueError("Zoned datetimes require seconds")
    return value


def validate_time(value: str) -> str:
    datetime.time.fromisoformat(value)
    return value


def validate_duration(value: str) -> str:
    pydantic.TypeAdapter(datetime.timedelta).validate_python(value)
    return value


def validate_rectangular_array(value: object) -> object:
    if not isinstance(value, list):
        raise ValueError("Expected an array")
    children = [item for item in value if isinstance(item, list)]
    if children:
        if len(children) != len(value) or len({len(item) for item in children}) != 1:
            raise ValueError("Array dimensions must be rectangular")
        for child in children:
            validate_rectangular_array(child)
    return value


def convert_read_value(value: object, kind: typing.Literal["numeric", "uuid", "enum", "bytes", "duration", "temporal"], dimensions: int) -> object:
    if value is None:
        return None
    if dimensions:
        if not isinstance(value, (list, tuple)):
            raise ValueError("ORM array value must be a sequence")
        return [convert_read_value(item, kind, dimensions - 1) for item in value]
    if kind in {"numeric", "uuid"}:
        return str(value)
    if kind == "bytes" and isinstance(value, bytes):
        return base64.b64encode(value).decode("ascii")
    if kind == "duration" and isinstance(value, datetime.timedelta):
        return pydantic.TypeAdapter(datetime.timedelta).dump_python(value, mode="json")
    if kind == "temporal" and isinstance(value, (datetime.datetime, datetime.date, datetime.time)):
        return value.isoformat()
    if kind == "enum" and isinstance(value, enum.Enum):
        return value.name
    return value


BigIntegerString = typing.Annotated[str, pydantic.StringConstraints(strict=True, pattern=INTEGER_PATTERN), pydantic.AfterValidator(validate_big_integer)]
NumericString = typing.Annotated[str, pydantic.StringConstraints(strict=True, pattern=NUMERIC_PATTERN)]
UUIDString = typing.Annotated[str, pydantic.StringConstraints(strict=True, pattern=UUID_PATTERN)]
DateString = typing.Annotated[str, pydantic.StringConstraints(strict=True, pattern=r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$"), pydantic.AfterValidator(validate_date)]
DatetimeString = typing.Annotated[str, pydantic.StringConstraints(strict=True, pattern=DATETIME_PATTERN), pydantic.AfterValidator(validate_datetime)]
TimeString = typing.Annotated[str, pydantic.StringConstraints(strict=True, pattern=TIME_PATTERN), pydantic.AfterValidator(validate_time)]
DurationString = typing.Annotated[str, pydantic.StringConstraints(strict=True, pattern=re.compile(DURATION_PATTERN)), pydantic.AfterValidator(validate_duration)]
BytesString = typing.Annotated[str, pydantic.StringConstraints(strict=True, pattern=BYTES_PATTERN)]
"""


TYPESCRIPT_WIRE_TYPES = r"""// Generated by devOS from SQLAlchemy DAO metadata.
import * as z from "zod";

const BigIntegerStringSchema = z.string().regex(/^-?[0-9]+$/).refine(value => /^-?[0-9]+$/.test(value) && BigInt(value) >= -9223372036854775808n && BigInt(value) <= 9223372036854775807n, "Bigint must fit the signed 64-bit PostgreSQL range");
const NumericStringSchema = z.string().regex(/^[+-]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?$/);
const DateStringSchema = z.iso.date().refine(value => !value.startsWith("0000-"));
const DatetimeStringSchema = z.iso.datetime({offset: true, local: true}).regex(/^[0-9]{4}-[0-9]{2}-[0-9]{2}T(?:[01][0-9]|2[0-3]):[0-5][0-9](?::[0-5][0-9](?:\.[0-9]{1,6})?)?(?:Z|[+-](?:0[0-9]|1[0-5]):[0-5][0-9])?$/).refine(value => !value.startsWith("0000-"));
const TimeStringSchema = z.string().regex(/^(?:[01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9](?:\.[0-9]{1,6})?(?:Z|[+-](?:0[0-9]|1[0-5]):[0-5][0-9])?$/);
const DurationStringSchema = z.string().regex(/^-?P(?=[0-9]|T[0-9])(?:[0-9]+(?:\.[0-9]+)?Y)?(?:[0-9]+(?:\.[0-9]+)?M)?(?:[0-9]+(?:\.[0-9]+)?W)?(?:[0-9]+(?:\.[0-9]+)?D)?(?:T(?=[0-9])(?:[0-9]+(?:\.[0-9]+)?H)?(?:[0-9]+(?:\.[0-9]+)?M)?(?:[0-9]+(?:\.[0-9]+)?S)?)?$/);
const BytesStringSchema = z.string().regex(/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/);

function isRectangularArray(value: unknown): boolean {
  if (!Array.isArray(value)) return false;
  const children = value.filter(Array.isArray);
  if (!children.length) return true;
  return children.length === value.length && new Set(children.map(item => item.length)).size === 1 && children.every(isRectangularArray);
}
"""


class GenerateResourceDtosUseCase:
    def __init__(self) -> None:
        pass

    def execute(
        self, resources: list[resource_schema.MappedResource]
    ) -> resource_schema.ResourceContracts:
        logging.info(
            "Generating Python/TypeScript DTOs for %s mapped resources", len(resources)
        )
        names = [resource.get_name() for resource in resources]
        if len(set(names)) != len(names):
            raise ValueError("DAO names produce conflicting resource names")
        resources = sorted(resources, key=lambda resource: resource.get_name())
        python_lines = [PYTHON_WIRE_TYPES]
        typescript_lines = [TYPESCRIPT_WIRE_TYPES]

        # Generate scalar models before finite relationship projections.
        for resource in resources:
            name = resource.get_name()
            fields = resource.get_fields()
            roles: dict[resource_schema.ResourceRole, str] = {
                "write": "Write",
                "patch": "Patch",
                "read": "Read",
                "identity": "Identity",
            }
            for role, suffix in roles.items():
                model_name = name + suffix
                selected = [field for field in fields if field.accepts_role(role)]
                python_lines.extend(
                    [
                        "",
                        "",
                        f"class {model_name}(pydantic.BaseModel):",
                        '    model_config = pydantic.ConfigDict(extra="forbid", from_attributes=True, allow_inf_nan=False)',
                    ]
                )
                python_lines.extend(
                    field.render_python_field(role) for field in selected
                )
                typescript_lines.append(
                    f"\nexport const {model_name}Schema = z.strictObject({{"
                )
                typescript_lines.extend(
                    field.render_zod_field(role) for field in selected
                )
                typescript_lines.extend(
                    [
                        "});",
                        f"export type {model_name} = z.infer<typeof {model_name}Schema>;",
                    ]
                )
                if role == "read":
                    python_lines.extend(
                        [
                            "",
                            '    @pydantic.model_validator(mode="before")',
                            "    @classmethod",
                            "    def read_orm_values(cls, value: object) -> object:",
                            '        if not hasattr(value, "__mapper__"):',
                            "            return value",
                            "        values = {name: getattr(value, name) for name in cls.model_fields}",
                        ]
                    )
                    python_lines.extend(
                        conversion
                        for field in fields
                        if (conversion := field.render_read_conversion()) is not None
                    )
                    python_lines.append("        return values")

        for resource in resources:
            name = resource.get_name()
            fields = resource.get_fields()
            model_name = name + "ReadRelationship"
            python_lines.extend(
                [
                    "",
                    "",
                    f"class {model_name}(pydantic.BaseModel):",
                    '    model_config = pydantic.ConfigDict(extra="forbid", from_attributes=True, allow_inf_nan=False)',
                ]
            )
            python_lines.extend(field.render_python_field("read") for field in fields)
            typescript_lines.append(
                f"\nexport const {model_name}Schema = z.strictObject({{"
            )
            typescript_lines.extend(field.render_zod_field("read") for field in fields)
            for relationship in resource.mapper.relationships:
                target_name = resource_schema.MappedResource(
                    relationship.mapper
                ).get_name()
                if target_name not in names:
                    raise ValueError(
                        f"Related resource {target_name} is absent from the selected ORM module"
                    )
                annotation = (
                    f"list[{target_name}Read]"
                    if relationship.uselist
                    else f"{target_name}Read | None"
                )
                zod_type = (
                    f"z.array({target_name}ReadSchema)"
                    if relationship.uselist
                    else f"{target_name}ReadSchema.nullable()"
                )
                python_lines.append(f"    {relationship.key}: {annotation}")
                typescript_lines.append(f"  {relationship.key!r}: {zod_type},")
            python_lines.extend(
                [
                    "",
                    '    @pydantic.model_validator(mode="before")',
                    "    @classmethod",
                    "    def read_orm_values(cls, value: object) -> object:",
                    '        if not hasattr(value, "__mapper__"):',
                    "            return value",
                    "        values = {name: getattr(value, name) for name in cls.model_fields}",
                ]
            )
            python_lines.extend(
                conversion
                for field in fields
                if (conversion := field.render_read_conversion()) is not None
            )
            python_lines.append("        return values")
            typescript_lines.extend(
                [
                    "});",
                    f"export type {model_name} = z.infer<typeof {model_name}Schema>;",
                ]
            )
        result = resource_schema.ResourceContracts(
            python="\n".join(python_lines) + "\n",
            typescript="\n".join(typescript_lines) + "\n",
        )
        ast.parse(result.python)
        logging.info("Generated resource DTO contracts")
        return result
