import ast
import logging
import re

from devOS.domain import relational


class GenerateRelationalDaoUseCase:
    def __init__(self) -> None:
        pass

    def execute(self, document: relational.SchemaDocument) -> str:
        logging.info("Generating SQLAlchemy DAOs for %s tables", len(document.tables))
        document = relational.SchemaDocument.model_validate_json(
            document.model_dump_json()
        )
        configuration = document.orm or relational.OrmConfiguration()
        namespace_names = {item.id: item.name.name for item in document.namespaces}
        table_variables = {
            table.id: f"table_{index}" for index, table in enumerate(document.tables)
        }
        class_names = {}
        attribute_names = {}
        for table in document.tables:
            words = [
                part for part in re.split(r"[^a-zA-Z0-9]+", table.name.name) if part
            ]
            default_name = (
                "".join(word[:1].upper() + word[1:] for word in words) + "DAO"
            )
            configured = next(
                (
                    item.class_name
                    for item in configuration.tables
                    if item.table_id == table.id
                ),
                default_name,
            )
            relational.OrmTable.require_class_name(configured)
            class_names[table.id] = configured
            if not any(
                constraint.kind == "primary_key" for constraint in table.constraints
            ):
                raise ValueError(
                    f"{table.id} needs a primary key before DAO generation"
                )
            for column in table.columns:
                configured_attribute = next(
                    (
                        item.attribute_name
                        for item in configuration.columns
                        if item.column_id == column.id
                    ),
                    column.name.name,
                )
                relational.OrmColumn.require_attribute_name(configured_attribute)
                attribute_names[column.id] = configured_attribute
            table_attributes = [attribute_names[column.id] for column in table.columns]
            if len(set(table_attributes)) != len(table_attributes):
                raise ValueError(f"{table.id} has conflicting ORM column aliases")
        if len(set(class_names.values())) != len(class_names):
            raise ValueError(
                "Default ORM class names collide. Assign distinct orm.tables class_name aliases"
            )
        lines = [
            "# Generated by devOS from the relational SchemaDocument.",
            "import sqlalchemy as sa",
            "import sqlalchemy.orm as orm",
            "import sqlalchemy.dialects.postgresql as pg",
            "",
            "",
            "class Base(orm.DeclarativeBase):",
            "    pass",
            "",
        ]
        enum_variables = {}
        for index, enum_type in enumerate(document.enums):
            variable = f"enum_{index}"
            enum_variables[enum_type.id] = variable
            values = ", ".join(repr(value) for value in enum_type.values)
            namespace = namespace_names[enum_type.namespace_id]
            lines.append(
                f"{variable} = pg.ENUM({values}, name={enum_type.name.name!r}, schema=sa.sql.quoted_name({namespace!r}, True), quote=True, metadata=Base.metadata)"
            )

        # Declare tables before FK constraints so all column targets are available.
        for table in document.tables:
            variable = table_variables[table.id]
            namespace = namespace_names[table.namespace_id]
            lines.extend(
                ["", f"{variable} = sa.Table({table.name.name!r}, Base.metadata,"]
            )
            for column in table.columns:
                lines.append("    " + column.render_sqlalchemy(document, table) + ",")
            for constraint in table.constraints:
                name = constraint.name.name if constraint.name else None
                if isinstance(constraint, relational.ForeignKey):
                    continue
                if isinstance(constraint, relational.CheckConstraint):
                    lines.append(
                        f"    sa.CheckConstraint({constraint.expression!r}, name={name!r}),"
                    )
                else:
                    constructor = (
                        "sa.PrimaryKeyConstraint"
                        if constraint.kind == "primary_key"
                        else "sa.UniqueConstraint"
                    )
                    column_names = ", ".join(
                        repr(
                            next(
                                column.name.name
                                for column in table.columns
                                if column.id == column_id
                            )
                        )
                        for column_id in constraint.column_ids
                    )
                    lines.append(
                        f"    {constructor}({column_names}, name={name!r}, deferrable={constraint.deferrable!r}, initially={'DEFERRED' if constraint.initially_deferred else 'IMMEDIATE'!r}),"
                    )
            lines.append(
                f"    schema=sa.sql.quoted_name({namespace!r}, True), quote=True, comment={table.description!r}, info={{'devos_id': {table.id!r}}},\n)"
            )
        for table in document.tables:
            variable = table_variables[table.id]
            for constraint in table.constraints:
                if not isinstance(constraint, relational.ForeignKey):
                    continue
                target = next(
                    item
                    for item in document.tables
                    if item.id == constraint.target_table_id
                )
                source_columns = [
                    next(column for column in table.columns if column.id == value)
                    for value in constraint.column_ids
                ]
                target_columns = [
                    next(column for column in target.columns if column.id == value)
                    for value in constraint.target_column_ids
                ]
                source_reference_list = ", ".join(
                    f"{variable}.c[{column.name.name!r}]" for column in source_columns
                )
                target_reference_list = ", ".join(
                    f"{table_variables[target.id]}.c[{column.name.name!r}]"
                    for column in target_columns
                )
                name = constraint.name.name if constraint.name else None
                lines.append(
                    f"{variable}.append_constraint(sa.ForeignKeyConstraint([{source_reference_list}], [{target_reference_list}], name={name!r}, ondelete={constraint.on_delete!r}, onupdate={constraint.on_update!r}, match={constraint.match!r}, deferrable={constraint.deferrable!r}, initially={'DEFERRED' if constraint.initially_deferred else 'IMMEDIATE'!r}, info={{'devos_id': {constraint.id!r}}}))"
                )
            for table_index in table.indexes:
                column_refs = ", ".join(
                    f"{variable}.c[{next(column.name.name for column in table.columns if column.id == value)!r}]"
                    for value in table_index.column_ids
                )
                lines.append(
                    f"sa.Index({table_index.name.name!r}, {column_refs}, unique={table_index.unique!r}, quote=True)"
                )
        for table in document.tables:
            variable = table_variables[table.id]
            properties = ", ".join(
                f"{attribute_names[column.id]!r}: {variable}.c[{column.name.name!r}]"
                for column in table.columns
            )
            lines.extend(
                [
                    "",
                    "",
                    f"class {class_names[table.id]}(Base):",
                    f"    __table__ = {variable}",
                    f"    __mapper_args__ = {{'properties': {{{properties}}}}}",
                ]
            )

        # Bind navigation to specific FK columns, including self/composite paths.
        used_attributes = {
            table.id: {attribute_names[column.id] for column in table.columns}
            for table in document.tables
        }
        for table in document.tables:
            for constraint in table.constraints:
                if not isinstance(constraint, relational.ForeignKey):
                    continue
                target = next(
                    item
                    for item in document.tables
                    if item.id == constraint.target_table_id
                )
                configured_relationship = next(
                    (
                        item
                        for item in configuration.relationships
                        if item.foreign_key_id == constraint.id
                    ),
                    None,
                )
                source_columns = [
                    next(column for column in table.columns if column.id == value)
                    for value in constraint.column_ids
                ]
                target_columns = [
                    next(column for column in target.columns if column.id == value)
                    for value in constraint.target_column_ids
                ]
                path_name = "_".join(
                    attribute_names[column.id] for column in source_columns
                )
                source_name = (
                    configured_relationship.attribute_name
                    if configured_relationship
                    else class_names[target.id].removesuffix("DAO").lower()
                    + "_via_"
                    + path_name
                )
                reverse_name = (
                    configured_relationship.reverse_attribute_name
                    if configured_relationship
                    and configured_relationship.reverse_attribute_name
                    else "referenced_by_"
                    + class_names[table.id].removesuffix("DAO").lower()
                    + "_via_"
                    + path_name
                )
                for table_id, attribute in [
                    relational.OrmNavigationBinding(table.id, source_name),
                    relational.OrmNavigationBinding(target.id, reverse_name),
                ]:
                    if attribute in used_attributes[table_id]:
                        raise ValueError(
                            f"{constraint.id} navigation alias {attribute!r} conflicts. Configure distinct orm.relationships names"
                        )
                    used_attributes[table_id].add(attribute)
                source_refs = [
                    f"{table_variables[table.id]}.c[{column.name.name!r}]"
                    for column in source_columns
                ]
                target_refs = [
                    f"{table_variables[target.id]}.c[{column.name.name!r}]"
                    for column in target_columns
                ]
                join = (
                    "sa.and_("
                    + ", ".join(
                        f"{source} == {target_ref}"
                        for source, target_ref in zip(source_refs, target_refs)
                    )
                    + ")"
                )
                foreign_keys = "[" + ", ".join(source_refs) + "]"
                remote_side = (
                    ", remote_side=[" + ", ".join(target_refs) + "]"
                    if table.id == target.id
                    else ""
                )
                cascade = (
                    configured_relationship.cascade
                    if configured_relationship
                    else "save-update, merge"
                )
                passive_deletes = (
                    "True" if cascade in {"all", "all, delete-orphan"} else repr("all")
                )
                unique_source = any(
                    isinstance(item, relational.KeyConstraint)
                    and set(item.column_ids) == set(constraint.column_ids)
                    for item in table.constraints
                )
                lines.append(
                    f"{class_names[table.id]}.{source_name} = orm.relationship({class_names[target.id]}, foreign_keys={foreign_keys}, primaryjoin={join}, back_populates={reverse_name!r}{remote_side})"
                )
                lines.append(
                    f"{class_names[target.id]}.{reverse_name} = orm.relationship({class_names[table.id]}, foreign_keys={foreign_keys}, primaryjoin={join}, back_populates={source_name!r}, uselist={not unique_source!r}, cascade={cascade!r}, passive_deletes={passive_deletes})"
                )
        result = "\n".join(lines) + "\n"
        ast.parse(result)
        logging.info("Generated SQLAlchemy DAOs")
        return result
