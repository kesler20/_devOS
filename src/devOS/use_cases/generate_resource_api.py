import ast
import logging

import sqlalchemy as sa

from devOS.domain import resource_api
from devOS.domain import resource_schema


class GenerateResourceApiUseCase:
    def __init__(self) -> None:
        pass

    def execute(
        self,
        resources: list[resource_schema.MappedResource],
        imports: resource_api.ResourceApiImports,
    ) -> str:
        logging.info("Generating CRUD routers for %s resources", len(resources))
        names = [resource.get_name() for resource in resources]
        if len(set(names)) != len(names):
            raise ValueError("Resource names must be unique")
        lines = [
            "# Generated by devOS from SQLAlchemy DAO metadata.",
            "import typing",
            "import fastapi",
            "import sqlalchemy.orm as orm",
            f"import {imports.dao_module} as dao",
            f"import {imports.dto_module} as dto",
            f"import {imports.crud_module} as crud",
            f"import {imports.session_module} as database",
            "",
            "router = fastapi.APIRouter()",
            "",
        ]
        for resource in sorted(resources, key=lambda item: item.get_name()):
            name = resource.get_name()
            route = resource_api.get_resource_path(name)
            fields = resource.get_fields()
            keys = resource.get_identity_fields()
            if not keys:
                raise ValueError(f"{name} needs a primary key for CRUD routes")
            declarations = []
            identity_values = []
            for field in keys:
                column_type = field.column.type
                if isinstance(column_type, (sa.JSON, sa.ARRAY, sa.LargeBinary)):
                    raise ValueError(
                        f"{name}.{field.name} needs a custom route for its non-path key type"
                    )
                annotation = (
                    field.render_python_type()
                    .replace("BigIntegerString", "dto.BigIntegerString")
                    .replace("NumericString", "dto.NumericString")
                    .replace("UUIDString", "dto.UUIDString")
                    .replace("DateString", "dto.DateString")
                    .replace("DatetimeString", "dto.DatetimeString")
                    .replace("TimeString", "dto.TimeString")
                    .replace("DurationString", "dto.DurationString")
                    .replace("pydantic.StrictStr", "str")
                )
                if isinstance(column_type, sa.Integer) and not isinstance(
                    column_type, sa.BigInteger
                ):
                    minimum = (
                        -32768
                        if isinstance(column_type, sa.SmallInteger)
                        else -2147483648
                    )
                    maximum = (
                        32767
                        if isinstance(column_type, sa.SmallInteger)
                        else 2147483647
                    )
                    annotation = f"typing.Annotated[int, fastapi.Path(ge={minimum}, le={maximum})]"
                elif isinstance(column_type, sa.String) and not isinstance(
                    column_type, sa.Enum
                ):
                    annotation = (
                        "str"
                        if column_type.length is None
                        else f"typing.Annotated[str, fastapi.Path(max_length={column_type.length})]"
                    )
                elif isinstance(column_type, sa.Float):
                    annotation = (
                        "typing.Annotated[float, fastapi.Path(allow_inf_nan=False)]"
                    )
                elif isinstance(column_type, sa.Boolean):
                    annotation = "bool"
                declarations.append(f"key_{field.name}: {annotation}")
                identity_values.append(f"{field.name!r}: key_{field.name}")
            path = (
                "/"
                + route
                + "/"
                + "/".join("{key_" + field.name + "}" for field in keys)
            )
            identity = (
                "crud.ReadEntityRequest(entity_id={"
                + ", ".join(identity_values)
                + "}).entity_id"
                if len(keys) > 1
                else "key_" + keys[0].name
            )
            # Identity's definition belongs to the installed bundle. No copied adapter is generated.
            relationships = []
            for relationship in resource.mapper.relationships:
                target = resource_schema.MappedResource(relationship.mapper).get_name()
                if target not in names:
                    raise ValueError(
                        f"Related resource {target} is absent from the ORM module"
                    )
                relationships.append(f"{relationship.key!r}: dto.{target}Read")
            lines.extend(
                [
                    f"{route}_spec = crud.CRUDSpec(orm_model=dao.{resource.mapper.class_.__name__}, write_in=dto.{name}Write, read_out=dto.{name}Read, patch_in=dto.{name}Patch, read_relationships_out=dto.{name}ReadRelationship, relationship_read_out={{"
                    + ", ".join(relationships)
                    + "})",
                    "",
                    f"def {route}_use_case(session: typing.Annotated[orm.Session, fastapi.Depends(database.{imports.session_provider})]):",
                    f"    return crud.CRUDUseCase(session, {route}_spec)",
                    "",
                ]
            )
            dependency = f"use_case: typing.Annotated[crud.CRUDUseCase, fastapi.Depends({route}_use_case)]"
            key_arguments = ", ".join([*declarations, dependency])
            operations = [
                resource_api.ResourceOperation(
                    "post",
                    "/" + route,
                    "create",
                    f"request: crud.WriteEntityRequest[dto.{name}Write], {dependency}",
                    f"crud.WriteEntityResponse[dto.{name}Read]",
                    "return use_case.write_entity(request)",
                    201,
                ),
                resource_api.ResourceOperation(
                    "get",
                    "/" + route,
                    "list",
                    dependency,
                    f"crud.ReadAllEntitiesResponse[dto.{name}Read]",
                    "return use_case.read_all_entities()",
                    200,
                ),
                resource_api.ResourceOperation(
                    "get",
                    path,
                    "read",
                    key_arguments,
                    f"crud.ReadEntityResponse[dto.{name}Read]",
                    f"result = use_case.read_entity(crud.ReadEntityRequest(entity_id={identity}))\n        if result.entity is None:\n            raise fastapi.HTTPException(status_code=404, detail='Entity not found')\n        return result",
                    200,
                ),
                resource_api.ResourceOperation(
                    "patch",
                    path,
                    "patch",
                    f"request: crud.WriteEntityRequest[dto.{name}Patch], {key_arguments}",
                    f"crud.WriteEntityResponse[dto.{name}Read]",
                    f"return use_case.write_entity(request, entity_id={identity})",
                    200,
                ),
                resource_api.ResourceOperation(
                    "delete",
                    path,
                    "delete",
                    key_arguments,
                    "crud.DeleteEntityResponse",
                    f"return use_case.delete_entity(crud.DeleteEntityRequest(entity_id={identity}))",
                    200,
                ),
                resource_api.ResourceOperation(
                    "get",
                    path + "/relationships",
                    "expanded",
                    key_arguments,
                    f"crud.ReadEntityRelationshipsResponse[dto.{name}ReadRelationship]",
                    f"result = use_case.read_entity_relationships(crud.ReadEntityRequest(entity_id={identity}))\n        if result.entity is None:\n            raise fastapi.HTTPException(status_code=404, detail='Entity not found')\n        return result",
                    200,
                ),
            ]
            for method, url, operation, arguments, response, body, status in operations:
                lines.extend(
                    [
                        "",
                        f"@router.{method}({url!r}, response_model={response}, status_code={status})",
                        f"def {operation}_{route}({arguments}):",
                        "    try:",
                        "        " + body,
                        "    except crud.EntityNotFoundError as error:",
                        "        raise fastapi.HTTPException(status_code=404, detail=str(error)) from error",
                        "    except crud.InvalidEntityInputError as error:",
                        "        raise fastapi.HTTPException(status_code=422, detail=str(error)) from error",
                        "    except crud.EntityConstraintError as error:",
                        "        raise fastapi.HTTPException(status_code=409, detail=str(error)) from error",
                    ]
                )
        result = "\n".join(lines) + "\n"
        ast.parse(result)
        logging.info("Generated CRUD routers")
        return result
