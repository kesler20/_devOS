import logging

from devOS.domain import relational


class GenerateRelationalSqlUseCase:
    def __init__(self) -> None:
        pass

    def execute(self, document: relational.SchemaDocument) -> str:
        logging.info(
            "Generating PostgreSQL creation SQL for %s tables", len(document.tables)
        )
        document = relational.SchemaDocument.model_validate_json(
            document.model_dump_json()
        )
        for table in document.tables:
            table.validate_expressions()
        statements = ["-- Generated by devOS from the relational SchemaDocument.\n"]
        for namespace in document.namespaces:
            if namespace.name.name != "public":
                statements.append(f"CREATE SCHEMA {namespace.name.render_sql()};")
        for enum_type in document.enums:
            namespace = next(
                item
                for item in document.namespaces
                if item.id == enum_type.namespace_id
            )
            values = ", ".join(
                "'" + value.replace("'", "''") + "'" for value in enum_type.values
            )
            statements.append(
                f"CREATE TYPE {namespace.name.render_sql()}.{enum_type.name.render_sql()} AS ENUM ({values});"
            )

        # Create every table before adding foreign keys so cyclic references work.
        for table in document.tables:
            definitions = [column.render_sql(document) for column in table.columns]
            for constraint in table.constraints:
                if isinstance(constraint, relational.ForeignKey):
                    continue
                definition = (
                    constraint.render_sql()
                    if isinstance(constraint, relational.CheckConstraint)
                    else constraint.render_sql(table)
                )
                definitions.append(definition)
            statements.append(
                f"CREATE TABLE {table.render_qualified_name(document)} (\n  "
                + ",\n  ".join(definitions)
                + "\n);"
            )
        for table in document.tables:
            for constraint in table.constraints:
                if not isinstance(constraint, relational.ForeignKey):
                    continue
                definition = constraint.render_sql(table, document)
                statements.append(
                    f"ALTER TABLE {table.render_qualified_name(document)} ADD {definition};"
                )
            for index in table.indexes:
                unique = "UNIQUE " if index.unique else ""
                statements.append(
                    f"CREATE {unique}INDEX {index.name.render_sql()} ON {table.render_qualified_name(document)} USING btree ({table.render_column_names(index.column_ids)});"
                )

        # SQL comments escape string literals without altering the stored text.
        for namespace in document.namespaces:
            if namespace.description is not None:
                description = namespace.description.replace("'", "''")
                statements.append(
                    f"COMMENT ON SCHEMA {namespace.name.render_sql()} IS '{description}';"
                )
        for enum_type in document.enums:
            if enum_type.description is not None:
                namespace = next(
                    item
                    for item in document.namespaces
                    if item.id == enum_type.namespace_id
                )
                description = enum_type.description.replace("'", "''")
                statements.append(
                    f"COMMENT ON TYPE {namespace.name.render_sql()}.{enum_type.name.render_sql()} IS '{description}';"
                )
        for table in document.tables:
            if table.description is not None:
                description = table.description.replace("'", "''")
                statements.append(
                    f"COMMENT ON TABLE {table.render_qualified_name(document)} IS '{description}';"
                )
            for column in table.columns:
                if column.description is not None:
                    description = column.description.replace("'", "''")
                    statements.append(
                        f"COMMENT ON COLUMN {table.render_qualified_name(document)}.{column.name.render_sql()} IS '{description}';"
                    )
        logging.info("Generated PostgreSQL creation SQL")
        return "\n\n".join(statements) + "\n"
