import pathlib

import pytest

from devOS.domain import relational
from devOS.use_cases import generate_relational_sql
from devOS.use_cases import import_relational_sql
from devOS import relational_cli


FIXTURES = pathlib.Path(__file__).parent / "fixtures/relational"


@pytest.mark.parametrize("fixture", sorted(FIXTURES.glob("valid*.json")), ids=lambda path: path.stem)
def test_creation_sql_initialization_preserves_supported_semantics(fixture):
    document = relational.SchemaDocument.model_validate_json(fixture.read_text())
    generator = generate_relational_sql.GenerateRelationalSqlUseCase()
    source = generator.execute(document)
    importer = import_relational_sql.ImportRelationalSqlUseCase()
    imported = importer.execute(source)
    assert generator.execute(imported) == source
    assert imported == importer.execute(source)
    assert imported.orm is None and imported.diagram is None


def test_import_handles_inline_keys_defaults_and_deferred_uniqueness():
    source = """
CREATE TABLE public.users (
  id SERIAL PRIMARY KEY,
  code TEXT UNIQUE,
  amount NUMERIC(10, 2) DEFAULT 0,
  parent INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
  CONSTRAINT named_unique UNIQUE(code, amount) DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT positive_amount CHECK(amount >= 0)
);
COMMENT ON COLUMN public.users.code IS 'Owner''s code';
"""
    document = import_relational_sql.ImportRelationalSqlUseCase().execute(source)
    table = document.tables[0]
    assert table.columns[0].serial and not table.columns[0].nullable
    assert table.columns[1].description == "Owner's code"
    foreign_key = next(item for item in table.constraints if isinstance(item, relational.ForeignKey))
    assert foreign_key.target_table_id == table.id
    assert foreign_key.on_delete == "SET NULL"
    unique = next(item for item in table.constraints if item.name and item.name.name == "named_unique")
    assert unique.deferrable and unique.initially_deferred


def test_import_preserves_identity_options_in_any_order():
    source = """CREATE TABLE x (id BIGINT GENERATED BY DEFAULT AS IDENTITY
        (CACHE 3 INCREMENT BY -2 START WITH 9 MAXVALUE 100 MINVALUE 1 CYCLE), PRIMARY KEY(id));"""
    document = import_relational_sql.ImportRelationalSqlUseCase().execute(source)
    identity = document.tables[0].columns[0].identity
    assert identity.generation == "by_default"
    assert identity.cache == 3 and identity.increment == -2
    assert identity.start == 9 and identity.min_value == 1 and identity.max_value == 100
    assert identity.cycle
    exported = generate_relational_sql.GenerateRelationalSqlUseCase().execute(document)
    reopened = import_relational_sql.ImportRelationalSqlUseCase().execute(exported)
    assert reopened.tables[0].columns[0].identity == identity


def test_import_preserves_explicit_not_deferrable_foreign_key():
    document = import_relational_sql.ImportRelationalSqlUseCase().execute("""
        CREATE TABLE parent(id int PRIMARY KEY);
        CREATE TABLE child(id int PRIMARY KEY, parent_id int REFERENCES parent(id) NOT DEFERRABLE);
    """)
    foreign_key = next(item for item in document.tables[1].constraints if isinstance(item, relational.ForeignKey))
    assert not foreign_key.deferrable and not foreign_key.initially_deferred


@pytest.mark.parametrize("source", [
    "CREATE VIEW v AS SELECT 1;",
    "CREATE TABLE x (id point);",
    "CREATE TABLE x (id int) PARTITION BY RANGE(id);",
    "CREATE TABLE x (id int, UNIQUE NULLS NOT DISTINCT(id));",
    "CREATE TABLE x (id int CHECK(id > 0) NOT ENFORCED);",
    "CREATE TABLE x (id integer[3]);",
    "CREATE TABLE x (id int); CREATE INDEX idx ON x(id DESC);",
    "CREATE TABLE x (id int); CREATE INDEX idx ON x((id + 1));",
    "CREATE TABLE x (id int); CREATE INDEX idx ON x(id) WHERE id > 0;",
    "CREATE TABLE x (id int); ALTER TABLE x DROP COLUMN id;",
    "CREATE TABLE x (id int); INSERT INTO x VALUES(1);",
    "CREATE TABLE IF NOT EXISTS x (id int);",
    "CREATE TABLE x (id int COLLATE something);",
    "CREATE TYPE status AS ENUM ('a',);",
    "CREATE TABLE x (id int GENERATED ALWAYS AS IDENTITY (CACHE));",
])
def test_unsupported_sql_fails_before_document_writes(tmp_path, source):
    input_path = tmp_path / "input.sql"
    input_path.write_text(source)
    destination = tmp_path / "output.json"
    assert relational_cli.main(["import-sql", str(input_path), "--output", str(destination)]) == 1
    assert not destination.exists()


def test_import_only_initializes_new_documents(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    source = tmp_path / "input.sql"
    source.write_text("CREATE TABLE x(id integer PRIMARY KEY);")
    assert relational_cli.main(["import-sql", "input.sql", "--output", "schema.json"]) == 0
    destination = tmp_path / "schema.json"
    previous = destination.read_bytes()
    assert relational_cli.main(["import-sql", "input.sql", "--output", "schema.json"]) == 1
    assert destination.read_bytes() == previous
