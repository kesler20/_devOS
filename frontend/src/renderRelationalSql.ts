import * as types from "./relational.types";
import { validateRelational } from "./validateRelational";

export function quoteSqlName(identifier: types.SqlIdentifier): string {
  return '"' + identifier.name.replace(/"/g, '""') + '"';
}

export function renderRelationalSql(value: types.SchemaDocument): string {
  const document = validateRelational(value);
  const namespaces = document.namespaces ?? [];
  const enums = document.enums ?? [];
  const tables = document.tables ?? [];
  const qualifiedName = (table: types.Table) => quoteSqlName(namespaces.find(item => item.id === table.namespace_id)!.name) + "." + quoteSqlName(table.name);
  const columnNames = (table: types.Table, ids: string[]) => ids.map(id => quoteSqlName(table.columns.find(item => item.id === id)!.name)).join(", ");
  const statements = ["-- Generated by devOS from the relational SchemaDocument.\n"];
  for (const namespace of namespaces) {
    if (namespace.name.name !== "public") statements.push(`CREATE SCHEMA ${quoteSqlName(namespace.name)};`);
  }
  for (const item of enums) {
    const namespace = namespaces.find(namespace => namespace.id === item.namespace_id)!;
    const values = item.values.map(value => "'" + value.replace(/'/g, "''") + "'").join(", ");
    statements.push(`CREATE TYPE ${quoteSqlName(namespace.name)}.${quoteSqlName(item.name)} AS ENUM (${values});`);
  }
  for (const table of tables) {
    const definitions: string[] = [];
    for (const column of table.columns) {
      const type = column.type;
      let sqlType = type.name.toUpperCase();
      if (type.enum_id) {
        const item = enums.find(item => item.id === type.enum_id)!;
        const namespace = namespaces.find(namespace => namespace.id === item.namespace_id)!;
        sqlType = quoteSqlName(namespace.name) + "." + quoteSqlName(item.name);
      }
      if (type.length != null) sqlType += `(${type.length})`;
      if (type.precision != null) sqlType += `(${type.precision}${type.scale != null ? ", " + type.scale : ""})`;
      if (type.time_precision != null) sqlType += `(${type.time_precision})`;
      sqlType += "[]".repeat(type.array_dimensions ?? 0);
      if (column.serial) sqlType = ({smallint: "SMALLSERIAL", integer: "SERIAL", bigint: "BIGSERIAL"} as Record<string, string>)[type.name];
      let definition = quoteSqlName(column.name) + " " + sqlType;
      if (column.identity) {
        const identity = column.identity;
        definition += ` GENERATED ${identity.generation === "always" ? "ALWAYS" : "BY DEFAULT"} AS IDENTITY`;
        const options: string[] = [];
        const settings: Array<[string, number | string | null | undefined]> = [
          ["START WITH", identity.start], ["INCREMENT BY", identity.increment],
          ["MINVALUE", identity.min_value], ["MAXVALUE", identity.max_value], ["CACHE", identity.cache],
        ];
        for (const [name, value] of settings) if (value != null) options.push(`${name} ${value}`);
        if (identity.cycle) options.push("CYCLE");
        if (options.length) definition += " (" + options.join(" ") + ")";
      }
      if (column.default != null) definition += " DEFAULT (" + column.default + ")";
      if (!(column.nullable ?? true)) definition += " NOT NULL";
      definitions.push(definition);
    }
    for (const constraint of table.constraints ?? []) {
      if (constraint.kind === "foreign_key") continue;
      let definition = constraint.name ? "CONSTRAINT " + quoteSqlName(constraint.name) + " " : "";
      if (constraint.kind === "check") definition += "CHECK (" + constraint.expression + ")";
      else {
        definition += (constraint.kind === "primary_key" ? "PRIMARY KEY" : "UNIQUE") + " (" + columnNames(table, constraint.column_ids) + ")";
        if (constraint.deferrable) definition += " DEFERRABLE INITIALLY " + (constraint.initially_deferred ? "DEFERRED" : "IMMEDIATE");
      }
      definitions.push(definition);
    }
    statements.push(`CREATE TABLE ${qualifiedName(table)} (\n  ${definitions.join(",\n  ")}\n);`);
  }
  for (const table of tables) {
    for (const constraint of table.constraints ?? []) {
      if (constraint.kind !== "foreign_key") continue;
      const target = tables.find(item => item.id === constraint.target_table_id)!;
      let definition = constraint.name ? "CONSTRAINT " + quoteSqlName(constraint.name) + " " : "";
      definition += "FOREIGN KEY (" + columnNames(table, constraint.column_ids) + ") REFERENCES " + qualifiedName(target) + " (" + columnNames(target, constraint.target_column_ids) + ")";
      definition += " MATCH " + (constraint.match ?? "SIMPLE") + " ON DELETE " + (constraint.on_delete ?? "NO ACTION") + " ON UPDATE " + (constraint.on_update ?? "NO ACTION");
      if (constraint.deferrable) definition += " DEFERRABLE INITIALLY " + (constraint.initially_deferred ? "DEFERRED" : "IMMEDIATE");
      statements.push(`ALTER TABLE ${qualifiedName(table)} ADD ${definition};`);
    }
    for (const index of table.indexes ?? []) {
      statements.push(`CREATE ${index.unique ? "UNIQUE " : ""}INDEX ${quoteSqlName(index.name)} ON ${qualifiedName(table)} USING btree (${columnNames(table, index.column_ids)});`);
    }
  }
  for (const namespace of namespaces) {
    if (namespace.description != null) statements.push(`COMMENT ON SCHEMA ${quoteSqlName(namespace.name)} IS '${namespace.description.replace(/'/g, "''")}';`);
  }
  for (const item of enums) {
    if (item.description != null) {
      const namespace = namespaces.find(namespace => namespace.id === item.namespace_id)!;
      statements.push(`COMMENT ON TYPE ${quoteSqlName(namespace.name)}.${quoteSqlName(item.name)} IS '${item.description.replace(/'/g, "''")}';`);
    }
  }
  for (const table of tables) {
    if (table.description != null) statements.push(`COMMENT ON TABLE ${qualifiedName(table)} IS '${table.description.replace(/'/g, "''")}';`);
    for (const column of table.columns) {
      if (column.description != null) statements.push(`COMMENT ON COLUMN ${qualifiedName(table)}.${quoteSqlName(column.name)} IS '${column.description.replace(/'/g, "''")}';`);
    }
  }
  return statements.join("\n\n") + "\n";
}
